/*
================
EmitCharacter

Emit main() and precache() for the character's models and aliases.
Body and head each require a direct model or an alias table; hat,
viewmodel and individual attachments may be empty.

Each entry point emits required attachments before optional ones.
Optional models share one useOptionalModels() block per entry point.
An alias chooses one model in main(); precache() registers all its models.

The helmet-side model is also saved for the game's helmet behaviour.

================
*/
void EmitCharacter( FILE *f, ConvertValue *cv ) {
	std::string body;
	std::string bodyAlias;
	std::string head;
	std::string headAlias;
	std::string hat;
	std::string hatAlias;
	std::string viewmodel;
	std::string model;
	std::string helmetSideModel;
	std::string voice;
	char optionalName[256];
	int pass;
	unsigned i;
	int optional;
	bool optionalBlock;

	fprintf( f, "// THIS FILE IS AUTOGENERATED, DO NOT MODIFY\n" );
	fprintf( f, "main()\n{\n" );

	body = cv->GetValue( "body" )->GetString();
	bodyAlias = cv->GetValue( "bodyAlias" )->GetString();
	if ( body.size() ) {
		if ( bodyAlias.size() ) {
			throw "cannot specify both body and bodyAlias";
		}
		fprintf( f, "\tself setModel(\"xmodel/%s\");\n",
			body.c_str() );
	} else if ( bodyAlias.size() ) {
		fprintf( f, "\tcharacter\\_utility::setModelFromArray(xmodelalias\\%s::main());\n",
			bodyAlias.c_str() );
	} else {
		throw "neither body nor bodyAlias were defined";
	}

	head = cv->GetValue( "head" )->GetString();
	headAlias = cv->GetValue( "headAlias" )->GetString();
	if ( head.size() ) {
		if ( headAlias.size() ) {
			throw "cannot specify both head and headAlias";
		}
		fprintf( f, "\tself attach(\"xmodel/%s\");\n",
			head.c_str() );
	} else if ( headAlias.size() ) {
		fprintf( f, "\tcharacter\\_utility::attachFromArray(xmodelalias\\%s::main());\n",
			headAlias.c_str() );
	} else {
		throw "neither head nor headAlias were defined";
	}

	hat = cv->GetValue( "hat" )->GetString();
	hatAlias = cv->GetValue( "hatAlias" )->GetString();
	if ( hat.size() ) {
		if ( hatAlias.size() ) {
			throw "cannot specify both hat and hatAlias";
		}
		fprintf( f, "\tself.hatModel = \"xmodel/%s\";\n",
			hat.c_str() );
		fprintf( f, "\tself attach(self.hatModel);\n" );
	} else if ( hatAlias.size() ) {
		fprintf( f, "\tself.hatModel = character\\_utility::randomElement(xmodelalias\\%s::main());\n",
			hatAlias.c_str() );
		fprintf( f, "\tself attach(self.hatModel);\n" );
	}

	viewmodel = cv->GetValue( "viewmodel" )->GetString();
	if ( viewmodel.size() ) {
		fprintf( f, "\tself setViewmodel(\"xmodel/%s\");\n",
			viewmodel.c_str() );
	}

	for ( pass = 0; pass <= 1; pass++ ) {
		optionalBlock = false;
		for ( i = 0; i < ARRAY_COUNT(miscParts); i++ ) {
			assert( strlen(miscParts[i]) + strlen("_required") < ARRAY_COUNT(optionalName) );
			sprintf( optionalName, "%s_required", miscParts[i] );
			optional = !cv->GetValue( optionalName )->GetInteger();
			assert( optional == 0 || optional == 1 );
			if ( optional != pass ) {
				continue;
			}

			model = cv->GetValue( miscParts[i] )->GetString();
			if ( !model.size() ) {
				if ( !optional ) {
					throw va( "%s is checked as required, but has no model given", miscParts[i] );
				}
				continue;
			}

			if ( optional && !optionalBlock ) {
				optionalBlock = true;
				fprintf( f, "\tif (character\\_utility::useOptionalModels())\n\t{\n" );
			}
			fprintf( f, "%sself attach(\"xmodel/%s\");\n", optional ? "\t\t" : "\t", model.c_str() );
		}
		for ( i = 0; i < ARRAY_COUNT(tagParts); i++ ) {
			assert( strlen(tagParts[i]) + strlen("_required") < ARRAY_COUNT(optionalName) );
			sprintf( optionalName, "%s_required", tagParts[i] );
			optional = !cv->GetValue( optionalName )->GetInteger();
			assert( optional == 0 || optional == 1 );
			if ( optional != pass ) {
				continue;
			}
			model = cv->GetValue( tagParts[i] )->GetString();
			if ( !model.size() ) {
				if ( !optional ) {
					// Required-tag errors use the miscellaneous-part name.
					throw va( "%s is checked as required, but has no model given", miscParts[i] );
				}
				continue;
			}
			if ( optional && !optionalBlock ) {
				optionalBlock = true;
				fprintf( f, "\tif (character\\_utility::useOptionalModels())\n\t{\n" );
			}
			fprintf( f, "%sself attach(\"xmodel/%s\", \"%s\");\n",
				optional ? "\t\t" : "\t", model.c_str(), tagParts[i] );
		}

		// Save the helmet-side model within the matching optional block.
		helmetSideModel = cv->GetValue( "TAG_HELMETSIDE" )->GetString();
		if ( helmetSideModel.size() ) {
			bool helmetSideOptional =
				!cv->GetValue( "TAG_HELMETSIDE_required" )->GetInteger();
			if ( helmetSideOptional == optionalBlock ) {
				if ( optionalBlock ) {
					fprintf( f, "\t" );
				}
				fprintf( f, "\tself.helmetSideModel = \"xmodel/%s\";\n",
					helmetSideModel.c_str() );
			}
		}
		if ( optionalBlock ) {
			fprintf( f, "\t}\n" );
		}

		// Refresh attachment values after writing this pass.
		// The next pass may query the same fields again.
		for ( i = 0; i < ARRAY_COUNT(miscParts); i++ ) {
			model = cv->GetValue( miscParts[i] )->GetString();
		}
		for ( i = 0; i < ARRAY_COUNT(tagParts); i++ ) {
			model = cv->GetValue( tagParts[i] )->GetString();
		}
	}

	// Always emit the voice field, including an empty value.
	voice = cv->GetValue( "voice" )->GetString();
	fprintf( f, "\tself.voice = \"%s\";\n", voice.c_str() );
	fprintf( f, "}\n" );
	fprintf( f, "\n" );
	// Alias tables need every model precached, although main() selects one.
	// The earlier checks guarantee body and head; hat and viewmodel may be empty.
	fprintf( f, "precache()\n{\n" );

	if ( body.size() ) {
		fprintf( f, "\tprecacheModel(\"xmodel/%s\");\n",
			body.c_str() );
	} else {
		fprintf( f, "\tcharacter\\_utility::precacheModelArray(xmodelalias\\%s::main());\n",
			bodyAlias.c_str() );
	}
	if ( head.size() ) {
		fprintf( f, "\tprecacheModel(\"xmodel/%s\");\n",
			head.c_str() );
	} else {
		fprintf( f, "\tcharacter\\_utility::precacheModelArray(xmodelalias\\%s::main());\n",
			headAlias.c_str() );
	}
	if ( hat.size() ) {
		fprintf( f, "\tprecacheModel(\"xmodel/%s\");\n",
			hat.c_str() );
	} else if ( hatAlias.size() ) {
		fprintf( f, "\tcharacter\\_utility::precacheModelArray(xmodelalias\\%s::main());\n",
			hatAlias.c_str() );
	}
	if ( viewmodel.size() ) {
		fprintf( f, "\tprecacheModel(\"xmodel/%s\");\n",
			viewmodel.c_str() );
	}

	/*
	 * Precache required and optional attachments in the same order as main().
	 * Optional precache calls use the same useOptionalModels() guard.
	 * Each part's _required field determines its pass; check the field-name
	 * buffer before adding the suffix. Empty required parts are errors here too.
	 * Open the optional block only when at least one model is present.
	 */
	for ( pass = 0; pass <= 1; pass++ ) {
		optionalBlock = false;
		for ( i = 0; i < ARRAY_COUNT(miscParts); i++ ) {
			assert( strlen(miscParts[i]) + strlen("_required") < ARRAY_COUNT(optionalName) );
			sprintf( optionalName, "%s_required", miscParts[i] );
			optional = !cv->GetValue( optionalName )->GetInteger();
			assert( optional == 0 || optional == 1 );
			if ( optional != pass ) {
				continue;
			}

			model = cv->GetValue( miscParts[i] )->GetString();
			if ( !model.size() ) {
				if ( !optional ) {
					throw va( "%s is checked as required, but has no model given", miscParts[i] );
				}
				continue;
			}

			if ( optional && !optionalBlock ) {
				optionalBlock = true;
				fprintf( f, "\tif (character\\_utility::useOptionalModels())\n\t{\n" );
			}
			fprintf( f, "%sprecacheModel(\"xmodel/%s\");\n", optional ? "\t\t" : "\t", model.c_str() );
		}
		for ( i = 0; i < ARRAY_COUNT(tagParts); i++ ) {
			assert( strlen(tagParts[i]) + strlen("_required") < ARRAY_COUNT(optionalName) );
			sprintf( optionalName, "%s_required", tagParts[i] );
			optional = !cv->GetValue( optionalName )->GetInteger();
			assert( optional == 0 || optional == 1 );
			if ( optional != pass ) {
				continue;
			}
			model = cv->GetValue( tagParts[i] )->GetString();
			if ( !model.size() ) {
				if ( !optional ) {
					// Required-tag errors use the miscellaneous-part name.
					throw va( "%s is checked as required, but has no model given", miscParts[i] );
				}
				continue;
			}
			if ( optional && !optionalBlock ) {
				optionalBlock = true;
				fprintf( f, "\tif (character\\_utility::useOptionalModels())\n\t{\n" );
			}
			fprintf( f, "%sprecacheModel(\"xmodel/%s\");\n",
				optional ? "\t\t" : "\t", model.c_str() );
		}
		if ( optionalBlock ) {
			fprintf( f, "\t}\n" );
		}
	}
	fprintf( f, "}\n" );
}

/*
=============
Convert
=============
*/
extern "C" __declspec( dllexport ) int Convert( ConvertValue *cv ) {
	static char gscPath[1024];
	FILE *f = 0;

	try {
		sprintf( gscPath, "%s%s.gsc", cv->GetTargetDirectory( 0 ), cv->GetName() );
		cv->AddTargetFile( gscPath );

		f = fopen( gscPath, "wb" );
		if ( !f ) {
			throw va( "Cannot open '%s'\n", gscPath );
		}

		EmitCharacter( f, cv );
		fclose( f );
		fflush( stdout );
		return 0;
	} catch ( char *message ) {
		printf( "\n************ ERROR ************\n" );
		printf( "%s\n", message );
		if ( f ) {
			fclose( f );
		}
		fflush( stdout );
		return 1;
	}
}
