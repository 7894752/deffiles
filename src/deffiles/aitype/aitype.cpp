/*
=============
EscapeString
=============
*/
std::string EscapeString( std::string text )
{
	int length = text.size();
	char *escaped = (char *)alloca( length * 2 + 1 );
	char *out = escaped;

	for ( int i = 0; i < length; i++ )
	{
		switch ( text[i] )
		{
		case '\n':
			*out++ = '\\';
			*out++ = 'n';
			break;

		case '\\':
			*out++ = '\\';
			*out++ = '\\';
			break;

		case '\t':
			*out++ = '\\';
			*out++ = 't';
			break;

		case '\r':
			*out++ = '\\';
			*out++ = 'r';
			break;

		case '"':
			*out++ = '\\';
			*out++ = '"';
			break;

		default:
			*out++ = text[i];
			break;
		}
	}
	*out = 0;

	return std::string( escaped );
}

/*
=============
EmitAIType
=============
*/
int EmitAIType( FILE *f, ConvertValue *cv )
{
	std::string team;
	static std::string characters[MAX_CHARACTERS];
	std::string character;
	std::string radiantModel;
	const char *color;
	const char *key;
	int numCharacters;
	int i;

	team = cv->GetValue( "team" )->GetString();
	if ( !stricmp( team.c_str(), "axis" ) )
	{
		color = "1.0 0.25 0.0";
	}
	else if ( !stricmp( team.c_str(), "allies" ) )
	{
		color = "0.0 0.25 1.0";
	}
	else if ( !stricmp( team.c_str(), "neutral" ) )
	{
		color = "0.5 0.5 0.5";
	}
	else
	{
		printf( "ERROR: invalid team '%s'\n", team.c_str() );
		return 1;
	}

	radiantModel = cv->GetValue( "radiantModel" )->GetString();

	fprintf( f, "// THIS FILE IS AUTOGENERATED, DO NOT MODIFY\n" );
	fprintf( f, "/*QUAKED actor_%s (%s) (-16 -16 0) (16 16 72) SPAWNER FORCESPAWN UNDELETABLE NOENEMYINFO\n", cv->GetName(), color );
	fprintf( f, "defaultmdl=\"xmodel/%s\"\n", radiantModel.c_str() );
	fprintf( f, "\"count\" -- max AI to ever spawn from this spawner\n" );
	fprintf( f, "SPAWNER -- makes this a spawner instead of a guy\n" );
	fprintf( f, "FORCESPAWN -- will try to delete an AI if spawning fails from too many AI\n" );
	fprintf( f, "UNDELETABLE -- this AI (or AI spawned from here) cannot be deleted to make room for FORCESPAWN guys\n" );
	fprintf( f, "NOENEMYINFO -- this AI when spawned will not get a snapshot of perfect info about all enemies\n" );
	fprintf( f, "*/\n" );
	fprintf( f, "main()\n{\n" );

	numCharacters = 0;
	for ( key = cv->GetNextKey( 0 ); key; key = cv->GetNextKey( key ) )
	{
		ConvertValue *value = cv->GetValue( key );

		if ( !value->IsPrimType() )
		{
			printf( "'%s' is not a primitive type\n", key );
			continue;
		}
		if ( !stricmp( key, "radiantModel" ) || !stricmp( key, "comments" ) )
		{
			continue;
		}

		if ( !strnicmp( key, "character", 9 ) )
		{
			assert( numCharacters < MAX_CHARACTERS );
			character = value->GetString();
			if ( character.size() )
			{
				characters[numCharacters] = character;
				numCharacters++;
			}
			continue;
		}

		// Primitive fields become properties on the spawned actor.

		switch ( value->GetPrimType() )
		{
		case CV_STRING:
			fprintf( f, "\tself.%s = \"%s\";\n", key, EscapeString( value->GetString() ).c_str() );
			break;

		case CV_INT:
			fprintf( f, "\tself.%s = %d;\n", key, value->GetInteger() );
			break;

		case CV_FLOAT:
			fprintf( f, "\tself.%s = %g;\n", key, value->GetFloat() );
			break;
		}
	}

	if ( !numCharacters )
	{
		printf( "\n************ ERROR ************\n" );
		printf( "No character specified\n" );
		return 1;
	}

	// A single character is called directly; otherwise pick one at random.
	// Keep the switch cases in the order of the characterN keys.
	fprintf( f, "\n" );

	if ( numCharacters == 1 )
	{
		fprintf( f, "\tcharacter\\%s::main();\n", characters[0].c_str() );
	}
	else
	{
		fprintf( f, "\tswitch(randomint(%d))\n", numCharacters );
		fprintf( f, "\t{\n" );
		for ( i = 0; i < numCharacters; i++ )
		{
			fprintf( f, "\tcase %d:\n", i );
			fprintf( f, "\t\tcharacter\\%s::main();\n", characters[i].c_str() );
			fprintf( f, "\t\tbreak;\n" );
		}
		fprintf( f, "\t}\n" );
	}

	fprintf( f, "}\n" );
	fprintf( f, "\n" );

	fprintf( f, "spawner()\n{\n" );
	assert( team.size() );
	fprintf( f, "\tself setspawnerteam(\"%s\");\n", team.c_str() );
	fprintf( f, "}\n" );
	fprintf( f, "\n" );

	fprintf( f, "precache()\n{\n" );
	for ( i = 0; i < numCharacters; i++ )
	{
		fprintf( f, "\tcharacter\\%s::precache();\n", characters[i].c_str() );
	}
	fprintf( f, "\n" );

	ConvertValue *weapon = cv->GetValue( "weapon" );
	if ( weapon->IsPrimType() && weapon->GetPrimType() == CV_STRING )
	{
		if ( *EscapeString( weapon->GetString() ).c_str() )
		{
			fprintf( f, "\tprecacheItem(\"%s\");\n", EscapeString( weapon->GetString() ).c_str() );
		}
	}
	ConvertValue *secondaryWeapon = cv->GetValue( "secondaryweapon" );
	if ( secondaryWeapon->IsPrimType() && secondaryWeapon->GetPrimType() == CV_STRING )
	{
		if ( *EscapeString( secondaryWeapon->GetString() ).c_str() )
		{
			fprintf( f, "\tprecacheItem(\"%s\");\n", EscapeString( secondaryWeapon->GetString() ).c_str() );
		}
	}
	ConvertValue *grenadeWeapon = cv->GetValue( "grenadeWeapon" );
	if ( grenadeWeapon->IsPrimType() && grenadeWeapon->GetPrimType() == CV_STRING )
	{
		if ( *EscapeString( grenadeWeapon->GetString() ).c_str() )
		{
			fprintf( f, "\tprecacheItem(\"%s\");\n", EscapeString( grenadeWeapon->GetString() ).c_str() );
		}
	}
	fprintf( f, "}\n" );

	return 0;
}

static char gscPath[1024];

/*
=============
Convert
=============
*/
extern "C" __declspec( dllexport ) int Convert( ConvertValue *cv )
{
	FILE *f;
	int result;

	sprintf( gscPath, "%s%s.gsc", cv->GetTargetDirectory( 0 ), cv->GetName() );
	cv->AddTargetFile( gscPath );

	f = fopen( gscPath, "wb" );
	if ( !f )
	{
		printf( "\n************ ERROR ************\n" );
		printf( "Cannot open '%s'\n", gscPath );
		fflush( stdout );
		return 1;
	}

	result = EmitAIType( f, cv );
	fclose( f );
	fflush( stdout );
	return result;
}
