/*
=============
EscapeString
=============
*/
std::string EscapeString( std::string text ) {
	int length = text.size();
	char *escaped = (char *)alloca( length * 2 + 1 ); // Each escape needs two bytes.
	char *out = escaped;

	for ( int i = 0; i < length; i++ ) {
		switch ( text[i] ) {
		case '\n':
			*out++ = '\\';
			*out++ = 'n';
			break;
		case '\\':
			*out++ = '\\';
			*out++ = '\\';
			break;
		case '\t':
			*out++ = '\\';
			*out++ = 't';
			break;
		case '\r':
			*out++ = '\\';
			*out++ = 'r';
			break;
		case '"':
			*out++ = '\\';
			*out++ = '"';
			break;
		default:
			*out++ = text[i];
			break;
		}
	}
	*out = 0;

	return std::string( escaped );
}

/*
=============
EmitMPType
=============
*/
int EmitMPType( FILE *f, ConvertValue *cv ) {
	static std::string characters[MAX_CHARACTERS];
	std::string character;
	const char *key;
	int numCharacters;
	int i;

	fprintf( f, "// THIS FILE IS AUTOGENERATED, DO NOT MODIFY\n" );
	fprintf( f, "main()\n{\n" );

	numCharacters = 0;
	for ( key = cv->GetNextKey( 0 ); key; key = cv->GetNextKey( key ) ) {
		ConvertValue *value = cv->GetValue( key );

		if ( !value->IsPrimType() ) {
			printf( "'%s' is not a primitive type\n", key );
			continue;
		}
		if ( !stricmp( key, "comments" ) ) {
			continue;
		}

		if ( !strnicmp( key, "character", 9 ) ) {
			assert( numCharacters < MAX_CHARACTERS );
			character = value->GetString();
			if ( character.size() ) {
				characters[numCharacters] = character;
				numCharacters++;
			}
			continue;
		}

		switch ( value->GetPrimType() ) {
		case CV_STRING:
			fprintf( f, "\tself.%s = \"%s\";\n", key, EscapeString( value->GetString() ).c_str() );
			break;
		case CV_INT:
			fprintf( f, "\tself.%s = %d;\n", key, value->GetInteger() );
			break;
		case CV_FLOAT:
			fprintf( f, "\tself.%s = %g;\n", key, value->GetFloat() );
			break;
		}
	}

	if ( !numCharacters ) {
		printf( "\n************ ERROR ************\n" );
		printf( "No character specified\n" );
		return 1;
	}

	// Choose one character when spawning; precache all possible characters.
	fprintf( f, "\n" );
	if ( numCharacters == 1 ) {
		fprintf( f, "\tcharacter\\%s::main();\n", characters[0].c_str() );
	} else {
		fprintf( f, "\tswitch(randomint(%d))\n", numCharacters );
		fprintf( f, "\t{\n" );
		for ( i = 0; i < numCharacters; i++ ) {
			fprintf( f, "\tcase %d:\n", i );
			fprintf( f, "\t\tcharacter\\%s::main();\n", characters[i].c_str() );
			fprintf( f, "\t\tbreak;\n" );
		}
		fprintf( f, "\t}\n" );
	}
	fprintf( f, "}\n" );
	fprintf( f, "\n" );

	fprintf( f, "precache()\n{\n" );
	for ( i = 0; i < numCharacters; i++ ) {
		fprintf( f, "\tcharacter\\%s::precache();\n", characters[i].c_str() );
	}
	fprintf( f, "}\n" );

	return 0;
}

static char gscPath[1024];

/*
=============
Convert
=============
*/
extern "C" __declspec( dllexport ) int Convert( ConvertValue *cv ) {
	FILE *f;
	int result;

	sprintf( gscPath, "%s%s.gsc", cv->GetTargetDirectory( 0 ), cv->GetName() );
	cv->AddTargetFile( gscPath );

	f = fopen( gscPath, "wb" );
	if ( !f ) {
		printf( "\n************ ERROR ************\n" );
		printf( "Cannot open '%s'\n", gscPath );
		fflush( stdout );
		return 1;
	}

	result = EmitMPType( f, cv );
	fclose( f );
	fflush( stdout );
	return result;
}
