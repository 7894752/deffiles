static char temp_buffer[MAX_VA_STRING];
static char string[MAX_VA_STRING];      // in case va is called by nested functions
static int index = 0;

/*
============
va

does a varargs printf into a temp buffer, so I don't need to have
varargs versions of all text functions.
FIXME: make this buffer size safe someday
============
*/
char *va( const char *format, ... ) {
	va_list argptr;
	char *buf;
	int len;

	va_start( argptr, format );
	vsprintf( temp_buffer, format, argptr );
	va_end( argptr );

	len = strlen( temp_buffer );
	assert( len < MAX_VA_STRING );

	if ( len + index >= MAX_VA_STRING - 1 ) {
		index = 0;
	}

	buf = &string[index];
	memcpy( buf, temp_buffer, len + 1 );

	index += len + 1;

	return buf;
}

/*
================
EmitXModelAlias

Build the model array returned by the generated main() function.
Empty model values are skipped; array indices follow the entry's key order.
================
*/
void EmitXModelAlias( FILE *f, ConvertValue *cv ) {
	std::string alias;
	static std::string aliases[MAX_XMODELALIAS];
	const char *key;
	int numAlias;
	int i;

	fprintf( f, "// THIS FILE IS AUTOGENERATED, DO NOT MODIFY\n" );
	fprintf( f, "main()\n{\n" );

	numAlias = 0;
	for ( key = cv->GetNextKey( 0 ); key; key = cv->GetNextKey( key ) ) {
		ConvertValue *value = cv->GetValue( key );

		if ( !value->IsPrimType() ) {
			printf( "'%s' is not a primitive type\n", key );
			continue;
		}

		if ( !strnicmp( key, "model", 5 ) ) {
			assert( numAlias < MAX_XMODELALIAS );
			alias = value->GetString();
			if ( alias.size() ) {
				aliases[numAlias] = alias;
				numAlias++;
			}
		}
	}

	if ( !numAlias ) {
		throw "no aliases defined";
	}

	for ( i = 0; i < numAlias; i++ ) {
		fprintf( f, "\ta[%d] = \"xmodel/%s\";\n", i, aliases[i].c_str() );
	}
	fprintf( f, "\treturn a;\n" );
	fprintf( f, "}\n" );
}

/*
=============
Convert
=============
*/
extern "C" __declspec( dllexport ) int Convert( ConvertValue *cv ) {
	static char gscPath[1024];
	FILE *f = 0;

	try {
		sprintf( gscPath, "%s%s.gsc", cv->GetTargetDirectory( 0 ), cv->GetName() );
		cv->AddTargetFile( gscPath );

		f = fopen( gscPath, "wb" );
		if ( !f ) {
			throw va( "Cannot open '%s'\n", gscPath );
		}

		EmitXModelAlias( f, cv );
		fclose( f );
		fflush( stdout );
		return 0;
	} catch ( char *message ) {
		printf( "\n************ ERROR ************\n" );
		printf( "%s\n", message );
		if ( f ) {
			fclose( f );
		}
		fflush( stdout );
		return 1;
	}
}
